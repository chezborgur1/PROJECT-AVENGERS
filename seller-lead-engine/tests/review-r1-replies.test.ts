// Regression tests for the reply-handling findings in docs/build/REVIEW_R1.md
// (items 8, 10, 11, 17 to 25). Each test names its item.

const NOW = new Date("2026-10-18T14:00:00Z");
const TODAY = "2026-10-18";
const config = testConfig();

function seed(stores: Stores, overrides: Partial<ProspectRow> = {}): { p: ProspectRow; touch: TouchRow } {
  const p = makeProspect({ status: "in_sequence", mailbox: MAILBOX, sequence_step: 1, next_touch_date: "2026-10-20", ...overrides });
  stores.prospects.upsert([p]);
  const touch: TouchRow = {
    touch_id: "T-000123",
    prospect_id: p.prospect_id,
    kind: "outreach",
    step: 1,
    mailbox: MAILBOX,
    to_email: p.email,
    subject: "Exit-readiness check for Example Air",
    body_sha256: "x",
    planned_for: "2026-10-13",
    status: "sent",
    mode: "send",
    message_id: "m0",
    thread_id: `thr-${p.prospect_id}`,
    draft_id: "",
    error: "",
    created_at: "2026-10-13T13:00:00Z",
    updated_at: "2026-10-13T13:00:00Z",
  };
  stores.touches.upsert([touch]);
  return { p, touch };
}

const run = (stores: Stores, messages: InboundMessage[], transport = new MemoryTransport()) =>
  offline(() => processInbox(stores, config, { now: NOW, today: TODAY, messages, transport }));

const QUOTE = [
  "On Tue, Oct 13, 2026 at 9:00 AM Frank Example <frank@ambadvisory-mail.example> wrote:",
  "> Hi John,",
  "> I am offering owners in Tampa a free exit-readiness check.",
  "> Reply 'unsubscribe' and I will not email you again.",
].join("\n");

describe("item 11 and 17: bottom-posted and inline replies", () => {
  it("keeps the owner's words written below the quote, so an opt-out there is caught", async () => {
    const text = `${QUOTE}\n\nPlease take me off your list.`;
    expect(stripQuoted(text)).toBe("Please take me off your list.");
    const stores = tempStores();
    const { p } = seed(stores);
    await run(stores, [inbound({ threadId: `thr-${p.prospect_id}`, from: p.email, text })]);
    expect(stores.replies.rows()[0]).toMatchObject({ class: "unsubscribe", opt_out: "Y" });
    expect(new Suppression(stores.suppression).check(p.email)).toBeDefined();
    expect(stores.prospects.rows()[0]!.status).toBe("dnc");
  });

  it("keeps inline answers between quoted questions and drops the quoted lines", () => {
    const text = [
      "On Tue, Oct 13, 2026 at 9:00 AM Frank Example <frank@x.example> wrote:",
      "> 1. Roughly what was revenue last full year?",
      "About $1.5M",
      "> 2. If you did sell, when might that be?",
      "Within 6 months",
    ].join("\n");
    expect(stripQuoted(text)).toBe("About $1.5M\nWithin 6 months");
  });

  it("still cuts unprefixed history after an attribution, and never reads our own footer as an opt-out", () => {
    const text = "Yes, send the questions.\n\nOn Tue, Oct 13, 2026 Frank wrote:\nHi John,\nReply 'unsubscribe' and I will not email you again.";
    expect(stripQuoted(text)).toBe("Yes, send the questions.");
    expect(classifyByRules(inbound({ text }), stripQuoted(text))).toBeNull();
  });
});

describe("item 8: List-Unsubscribe mailto requests", () => {
  it("reads 'unsubscribe T-000123' in the subject as an opt-out, even with a machine-written body", () => {
    const msg = inbound({ subject: "unsubscribe T-000123", text: "This message was automatically generated by Gmail." });
    expect(classifyByRules(msg, stripQuoted(msg.text))).toMatchObject({ class: "unsubscribe", optOut: true });
  });

  it("finds the prospect from the touch id when the request comes from another address in a new thread", async () => {
    const stores = tempStores();
    const { p } = seed(stores);
    await run(stores, [inbound({ threadId: "brand-new-thread", from: "owner.personal@forwarded.example", subject: "unsubscribe T-000123", text: "" })]);
    expect(stores.replies.rows()[0]).toMatchObject({ prospect_id: p.prospect_id, class: "unsubscribe" });
    const s = new Suppression(stores.suppression);
    expect(s.check(p.email)).toBeDefined();
    expect(s.check("owner.personal@forwarded.example")).toBeDefined();
    expect(stores.prospects.rows()[0]!.status).toBe("dnc");
  });
});

describe("item 10: a failure after classification is retried", () => {
  it("leaves the reply unprocessed when the suppression write fails, and suppresses on the next run", async () => {
    const stores = tempStores();
    const { p } = seed(stores);
    const msg = inbound({ threadId: `thr-${p.prospect_id}`, from: p.email, text: "Please stop emailing me." });
    const real = stores.suppression.upsert.bind(stores.suppression);
    const realAppend = stores.suppression.append.bind(stores.suppression);
    stores.suppression.upsert = () => {
      throw new Error("EBUSY: suppression.csv is open in Excel");
    };
    stores.suppression.append = stores.suppression.upsert;
    const first = await run(stores, [msg]);
    expect(first.errors[0]!.error).toMatch(/will retry/);
    expect(stores.replies.rows()[0]).toMatchObject({ class: "" });

    stores.suppression.upsert = real;
    stores.suppression.append = realAppend;
    const second = await run(stores, [msg]);
    expect(second.duplicates).toBe(0);
    expect(stores.replies.rows()[0]).toMatchObject({ class: "unsubscribe", error: "" });
    expect(new Suppression(stores.suppression).check(p.email)).toBeDefined();
  });
});

describe("item 18: complaint wording in context", () => {
  it("does not treat a spam folder, a spam question or a lawyer who reviews paperwork as a complaint", () => {
    for (const text of [
      "Found this in my spam folder. Yes, I'm interested, send the questions.",
      "Your email went to spam, but yes.",
      "Is this spam? Who are you?",
      "Yes interested. I will have my lawyer look over anything first.",
      "My attorney handles contracts for us, happy to talk.",
    ]) {
      expect(detectComplaint(text), text).toBe(false);
    }
  });

  it("still catches spam said of the email and a lawyer as a threat", () => {
    for (const text of ["This is spam.", "Stop spamming me.", "You will hear from my lawyer.", "My lawyer will contact you.", "I am calling my attorney about this."]) {
      expect(detectComplaint(text), text).toBe(true);
    }
  });
});

describe("item 19: 'are you a bot?' keeps the owner's facts", () => {
  it("answers as asks_if_ai and still records the acceptance from the same reply", async () => {
    const p = makeProspect();
    const msg = inbound({ text: "Is this a real person? If so, yes, send the questions." });
    const cls = await offline(() => classifyReply(msg, { prospect: p, config }));
    expect(cls.class).toBe("asks_if_ai");
    expect(cls.facts.wants_readiness_check).toBe("Y");
  });
});

describe("item 20: band answers", () => {
  it("parses money and percent bands as stated, never as one figure", () => {
    expect(statedSde(makeLead(makeProspect(), { sde_band: "$250K to $500K" }))).toEqual({ low: 250_000, high: 500_000 });
    expect(parsePercentRange("10% to 30%")).toEqual({ low: 10, high: 30 });
    expect(parsePercentRange("under 10%")).toEqual({ low: 0, high: 10 });
    expect(parsePercentRange("over 60%")).toEqual({ low: 60, high: 100 });
    expect(parsePercentRange("about 25 percent")).toEqual({ low: 25, high: 25 });
    expect(parsePercentRange("a few")).toBeUndefined();
  });

  it("counts a band as an answer and scores it", () => {
    const p = makeProspect();
    const lead = makeLead(p, { revenue_band: "$1M to $2M", sde_band: "$250K to $500K", recurring_revenue_band: "30% to 60%", top_customer_band: "under 10%" });
    const asked = (key: string) => isAnswered(lead, INTAKE_QUESTIONS.find((q) => q.key === key)!);
    expect(["sde", "recurring", "top_customer"].every(asked)).toBe(true);
    const q = qualScore(lead, config);
    expect(q.missing).not.toContain("sde");
    expect(q.reasons.join(" ")).toMatch(/Owner earnings \$250K to \$500K/);
    expect(q.reasons.join(" ")).toMatch(/Readiness facts/);
  });

  it("gives a wider range from both ends of an SDE band, and withholds one for an open-ended band", () => {
    const p = makeProspect();
    const row: MultipleRow = { key: "hvac", vertical: "HVAC businesses", method: "sde", low: 2, mid: 2.5, high: 3, size_band: "all", source: "BizBuySell", source_url: "https://example.test", as_of: "2026", verified: true, verified_by: "test", notes: "" };
    const banded = buildReadinessCheck(makeLead(p, { sde_band: "$250K to $500K" }), p, config, { today: TODAY, multiples: [row] });
    expect(banded.range).toMatchObject({ low: 500_000, high: 1_500_000 });
    expect(banded.range!.basis).toMatch(/both ends of the owner earnings band of \$250K to \$500K/);
    const open = buildReadinessCheck(makeLead(p, { sde_band: "over $1M" }), p, config, { today: TODAY, multiples: [row] });
    expect(open.range).toBeUndefined();
    expect(open.rangeWithheld).toMatch(/EBITDA/);
  });

  it("asks the timeline with options that each map to one stored value", () => {
    expect(INTAKE_QUESTIONS.find((q) => q.key === "timeline")!.text).toMatch(/within 6 months, 6 to 12 months, 1 to 2 years, or further out/);
  });
});

describe("item 21: a full mailbox is a soft bounce", () => {
  it("keeps a live address off the suppression list when the DSN says 5.2.2 or over quota", () => {
    const dsn = (text: string) => inbound({ from: "Mail Delivery Subsystem <mailer-daemon@googlemail.com>", subject: "Delivery Status Notification (Failure)", text });
    expect(detectBounce(dsn("552-5.2.2 The email account that you tried to reach is over quota."))).toMatchObject({ type: "soft", code: "5.2.2" });
    expect(detectBounce(dsn("Final-Recipient: rfc822; bob@acme.example\nStatus: 5.2.2\nDiagnostic-Code: smtp; 552 mailbox full"))).toMatchObject({ type: "soft" });
    expect(detectBounce(dsn("550 5.1.1 The email account that you tried to reach does not exist."))).toMatchObject({ type: "hard", code: "5.1.1" });
  });
});

describe("item 22: the keyword fallback reads negations", () => {
  it("does not read 'not sure' or 'not interested in selling' as interest", () => {
    expect(classifyByKeywords("Not sure what this is about.").class).not.toBe("interested");
    expect(classifyByKeywords("I'm not sure I'm interested in selling.").class).not.toBe("interested");
    expect(classifyByKeywords("Sure, send it over.")).toMatchObject({ class: "interested", facts: { wants_readiness_check: "Y" } });
    expect(classifyByKeywords("No problem, yes I'm interested.").class).toBe("interested");
    expect(classifyByKeywords("Tell me more about how this works").facts.wants_readiness_check).toBeUndefined();
  });
});

describe("item 23: no promise of a check to a business outside the range", () => {
  it("makes no interested draft when the same reply puts the business below AMB's size", async () => {
    const stores = tempStores();
    const { p } = seed(stores);
    const t = new MemoryTransport();
    // The Claude path states the revenue; an injected classifier stands in for it.
    const classify = async () => ({ class: "interested" as const, classifier: "claude" as const, optOut: false, complaint: false, facts: { revenue: 300_000 }, notes: "" });
    await offline(() =>
      processInbox(stores, config, { now: NOW, today: TODAY, messages: [inbound({ threadId: `thr-${p.prospect_id}`, from: p.email, text: "Sure, we do about $300K a year." })], transport: t, classify }),
    );
    expect(t.delivered).toHaveLength(0);
    const lead = stores.leads.rows()[0]!;
    expect(lead.stage).toBe("lost");
    expect(lead.next_action).toMatch(/outside the size AMB serves/);
  });
});
